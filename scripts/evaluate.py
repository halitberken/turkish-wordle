"""Evaluate agents on the answer list (unlimited guesses by default).

Writes <out-dir>/baselines.json, baselines.md and guess_distribution.png.
"""

from __future__ import annotations

import argparse
import json
import random
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import plot_style as ps  # noqa: E402

from wordle_tr import RESULTS_DIR  # noqa: E402
from wordle_tr.agents import AGENTS, make_agent  # noqa: E402
from wordle_tr.alphabet import sort_key, to_upper  # noqa: E402
from wordle_tr.feedback import pattern_to_emoji  # noqa: E402
from wordle_tr.filters import FILTER_NAMES, make_filter  # noqa: E402
from wordle_tr.simulate import aggregate, evaluate, summarize  # noqa: E402
from wordle_tr.stats import one_letter_families  # noqa: E402
from wordle_tr.words import load_answers, load_guesses  # noqa: E402

LIMIT = 6


def run_agent(name: str, seeds: list[int], answers, guesses, filter_fn, max_guesses, words) -> dict:
    agent_runs = []
    for seed in seeds:
        agent = make_agent(name, seed)
        results = evaluate(agent, answers, guesses, filter_fn, max_guesses, words)
        summary = summarize(results, name, LIMIT)
        agent_runs.append((seed, results, summary))
        print(f"  {name:<10} seed {seed}: mean {summary.mean:.4f}, within {LIMIT}: "
              f"{summary.within_limit_pct:.2f} %, max {summary.max}, "
              f"{summary.total_time_s:.1f} s", flush=True)
        if agent.deterministic:
            break

    families: dict[str, tuple[str, int]] = {}
    for pattern, members in one_letter_families(answers):
        for word in members:
            if word not in families or len(members) > families[word][1]:
                families[word] = (pattern, len(members))

    first_results = agent_runs[0][1]
    failed = [
        {
            "answer": r.answer,
            "guesses": r.guesses,
            "patterns": [pattern_to_emoji(p) for p in r.patterns],
            "candidates_after": r.candidates_after,
            "family": list(families.get(r.answer, ("", 1))),
        }
        for r in sorted(first_results, key=lambda r: (-r.num_guesses, sort_key(r.answer)))
        if not (r.solved and r.num_guesses <= LIMIT)
    ]
    return {
        "deterministic": agent.deterministic,
        "seeds": [seed for seed, _, _ in agent_runs],
        "first_guess": first_results[0].guesses[0],
        "aggregate": aggregate([s for _, _, s in agent_runs]),
        "runs": [{"seed": seed, **s.to_dict(), "guesses": [r.num_guesses for r in results]}
                 for seed, results, s in agent_runs],
        "failed_games": failed,
        "failed_games_with_one_letter_neighbour": sum(bool(g["family"][0]) for g in failed),
    }


def write_markdown(path: Path, report: dict, command: str) -> None:
    cfg = report["config"]
    limit = "unlimited guesses" if cfg["max_guesses"] is None else f"max {cfg['max_guesses']} guesses"
    lines = [
        "# Baseline results",
        "",
        f"Generated by `{command}`.",
        f"{cfg['games']:,} hidden words (of {cfg['answers']:,} answers), {limit}, "
        f"filter `{cfg['filter']}`. Mean ± sample standard deviation over seeds for random agents. "
        "Times are machine-dependent.",
        "",
        f"| Agent | Runs | First guess | Mean guesses | % solved ≤ {LIMIT} | Failures (> {LIMIT}) "
        "| Max | Agent ms / guess | Filter ms / guess |",
        "| --- | ---: | --- | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for name, data in report["agents"].items():
        a = data["aggregate"]
        runs = "1" if data["deterministic"] else f"{a['runs']} seeds"
        first = to_upper(data["first_guess"]) + ("" if data["deterministic"] else " (seed 0)")
        if data["deterministic"]:
            mean, within, fails = f"{a['mean']:.4f}", f"{a['within_limit_pct']:.2f}", f"{a['failures']:.0f}"
        else:
            mean = f"{a['mean']:.4f} ± {a['mean_std']:.4f}"
            within = f"{a['within_limit_pct']:.2f} ± {a['within_limit_pct_std']:.2f}"
            fails = f"{a['failures']:.1f}"
        lines.append(f"| {name} | {runs} | {first} | {mean} | {within} | {fails} | {a['max']} "
                     f"| {a['mean_time_per_guess_ms']:.3f} | {a['mean_filter_time_ms']:.3f} |")

    lengths = sorted({int(k) for d in report["agents"].values() for k in d["aggregate"]["histogram"]})
    names = list(report["agents"])
    lines += ["", "## Guess-count distribution (number of games)", "",
              "| Guesses | " + " | ".join(names) + " |",
              "| ---: | " + " | ".join("---:" for _ in names) + " |"]
    for k in lengths:
        cells = []
        for name in names:
            value = report["agents"][name]["aggregate"]["histogram"].get(str(k), 0)
            cells.append(f"{value:.0f}" if report["agents"][name]["deterministic"] else f"{value:.1f}")
        lines.append(f"| {k} | " + " | ".join(cells) + " |")

    lines += ["", "## Hardest words (seed 0 for random agents)", ""]
    for name, data in report["agents"].items():
        hardest = ", ".join(f"{to_upper(w)} {n}" for w, n in data["runs"][0]["hardest"])
        lines.append(f"* **{name}**: {hardest}")

    for name, data in report["agents"].items():
        if not data["deterministic"] or not data["failed_games"]:
            continue
        lines += ["", f"## Games the {name} agent does not solve within {LIMIT}", "",
                  "| Answer | Guesses | Game | Candidates left after each guess | One-letter family |",
                  "| --- | ---: | --- | --- | --- |"]
        for game in data["failed_games"]:
            moves = " → ".join(f"{to_upper(g)} {p}" for g, p in zip(game["guesses"], game["patterns"]))
            family = f"{to_upper(game['family'][0])} ({game['family'][1]} words)" if game["family"][0] else "–"
            lines.append(f"| {to_upper(game['answer'])} | {len(game['guesses'])} | {moves} | "
                         f"{', '.join(map(str, game['candidates_after']))} | {family} |")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def plot_distribution(path: Path, report: dict) -> None:
    names = list(report["agents"])
    lengths = list(range(1, max(d["aggregate"]["max"] for d in report["agents"].values()) + 1))
    games = report["config"]["games"]
    n = len(names)
    width = min(0.8 / n, 0.32)

    fig, ax = ps.new_figure(9, 4.6, rect=(0.07, 0.1, 0.9, 0.68))
    shares = {name: [100.0 * report["agents"][name]["aggregate"]["histogram"].get(str(k), 0) / games
                     for k in lengths] for name in names}
    top = max(max(v) for v in shares.values())
    ax.set_xlim(0.4, len(lengths) + 0.6)
    ax.set_ylim(0, (int(top / 10) + 1) * 10)
    ax.axvspan(LIMIT + 0.5, len(lengths) + 0.6, color=ps.GRID, alpha=0.45, linewidth=0, zorder=0)
    ax.text(LIMIT + 0.6, ax.get_ylim()[1] * 0.97, f"not solved within {LIMIT}", fontsize=8.5,
            color=ps.INK_SECONDARY, va="top")
    ax.set_xticks(lengths)
    ax.set_xticklabels([str(k) for k in lengths], color=ps.INK_SECONDARY)
    ax.set_xlabel("guesses needed", color=ps.INK_MUTED, fontsize=9)
    ax.yaxis.set_major_formatter(lambda v, _: f"{v:.0f}%")
    entries = []
    for j, name in enumerate(names):
        offset = (j - (n - 1) / 2) * (width + 0.03)
        color = ps.SERIES[j % len(ps.SERIES)]
        ps.rounded_bars(ax, [k + offset for k in lengths], shares[name], width, [color] * len(lengths))
        a = report["agents"][name]["aggregate"]
        label = f"{name} (mean {a['mean']:.2f}" + ("" if report["agents"][name]["deterministic"]
                                                    else f", {a['runs']} seeds") + ")"
        entries.append((label, color))
    ps.legend(ax, entries, loc="upper left")
    ps.title(fig, "How many guesses each agent needs",
             f"share of the {games:,} hidden words, unlimited guesses")
    ps.save(fig, path)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--agent", action="append", choices=sorted(AGENTS),
                        help="agent to evaluate (repeatable; default: random and frequency)")
    parser.add_argument("--sample", type=int, metavar="N",
                        help="play only N randomly chosen hidden words (candidates are still all answers)")
    parser.add_argument("--sample-seed", type=int, default=1234, help="seed for --sample (default 1234)")
    parser.add_argument("--filter", choices=FILTER_NAMES, default="feedback",
                        help="candidate filter (results are identical, only speed differs)")
    parser.add_argument("--seeds", type=int, default=5, metavar="N",
                        help="random agents run with seeds 0..N-1 (default 5)")
    parser.add_argument("--max-guesses", type=int, default=None,
                        help="guess limit per game (default: unlimited)")
    parser.add_argument("--out-dir", type=Path, default=RESULTS_DIR, help="output folder")
    args = parser.parse_args()

    answers, guesses = load_answers(), load_guesses()
    words = None
    if args.sample:
        words = sorted(random.Random(args.sample_seed).sample(answers, args.sample), key=sort_key)
    names = args.agent or ["random", "frequency"]
    filter_fn = make_filter(args.filter, answers, guesses)

    print(f"evaluating {', '.join(names)} on {len(words or answers):,} words "
          f"(filter {args.filter}, {'unlimited' if args.max_guesses is None else args.max_guesses} guesses)")
    report = {
        "config": {
            "answers": len(answers),
            "guesses": len(guesses),
            "games": len(words or answers),
            "sample": args.sample,
            "sample_seed": args.sample_seed if args.sample else None,
            "filter": args.filter,
            "max_guesses": args.max_guesses,
            "limit": LIMIT,
            "seeds": list(range(args.seeds)),
            "words": words or answers,
        },
        "agents": {name: run_agent(name, list(range(args.seeds)), answers, guesses, filter_fn,
                                   args.max_guesses, words) for name in names},
    }

    args.out_dir.mkdir(parents=True, exist_ok=True)
    command = "python scripts/evaluate.py" + "".join(f" {a}" for a in sys.argv[1:])
    (args.out_dir / "baselines.json").write_text(
        json.dumps(report, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    write_markdown(args.out_dir / "baselines.md", report, command)
    plot_distribution(args.out_dir / "guess_distribution.png", report)

    print()
    for name, data in report["agents"].items():
        a = data["aggregate"]
        spread = "" if data["deterministic"] else f" ± {a['mean_std']:.4f}"
        print(f"{name:<10} mean {a['mean']:.4f}{spread}, within {LIMIT}: {a['within_limit_pct']:.2f} %, "
              f"failures {a['failures']:.1f}, max {a['max']}, first guess {to_upper(data['first_guess'])}")
    print(f"wrote {args.out_dir / 'baselines.json'}, baselines.md and guess_distribution.png")


if __name__ == "__main__":
    main()
